// assets/brand/*.svg (design-system export) → components/brand/BeavoBrand.tsx.
// Never redraw the brand art by hand: replace the SVGs and run `node scripts/build-brand.mjs`.
import { readFileSync, writeFileSync } from 'node:fs';

const TAGS = { g: 'G', circle: 'Circle', ellipse: 'Ellipse', path: 'Path', rect: 'Rect' };
const MARKS = [
  ['BeavoMark', 'mark.svg', 'Beavo', "The logo: Beavo's head."],
  ['BeavoWordmark', 'wordmark-ink.svg', 'Beavo', 'Outlined wordmark; pass `color` (ink by default, cream on dark grounds, teal).'],
  ['BeavoLockup', 'lockup-horizontal.svg', 'Beavo', 'Default lockup for cream and white grounds.'],
  ['BeavoWave', 'beavo-wave.svg', 'Beavo', 'Beavo waving — intro, empty states.'],
];

const toJsx = (svg) =>
  svg
    .replace(/<title>.*?<\/title>/, '')
    .replace(/^<svg[^>]*>|<\/svg>\s*$/g, '')
    .replace(/<(\/?)(\w+)/g, (_, slash, tag) => `<${slash}${TAGS[tag] ?? tag}`)
    .replace(/><\/(Circle|Ellipse|Path|Rect)>/g, ' />')
    .replace(/(?<=<(Circle|Ellipse|Path|Rect)\b[^>]*[^/])>/g, ' />')
    .replace(/stroke-(width|linecap|linejoin)/g, (_, k) => `stroke${k[0].toUpperCase()}${k.slice(1)}`)
    .trim();

const components = MARKS.map(([name, file, label, doc]) => {
  const svg = readFileSync(new URL(`../assets/brand/${file}`, import.meta.url), 'utf8');
  const [, , , w, h] = svg.match(/viewBox="(\S+) (\S+) (\S+) (\S+)"/);
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  let body = toJsx(svg);
  if (name === 'BeavoWordmark') body = body.replace(/fill="#22302E"/, 'fill={color}');
  const args = name === 'BeavoWordmark' ? `{ width = ${w}, color = '#22302E', ...rest }` : `{ width = ${w}, ...rest }`;
  return `/** ${doc} */
export function ${name}(${args}: LogoProps) {
  return (
    <Svg viewBox="${viewBox}" width={width} height={(width * ${h}) / ${w}} accessibilityRole="image" accessibilityLabel="${label}" {...rest}>
      ${body}
    </Svg>
  );
}`;
});

writeFileSync(
  new URL('../components/brand/BeavoBrand.tsx', import.meta.url),
  `// Generated by scripts/build-brand.mjs from assets/brand/*.svg — never edit or redraw; regenerate.
import Svg, { Circle, Ellipse, G, Path, Rect } from 'react-native-svg';
import type { SvgProps } from 'react-native-svg';

type LogoProps = SvgProps & { width?: number; color?: string };

${components.join('\n\n')}
`,
);
