// design/tokens.json (copied from the Beavo design system) → tailwind.preset.js.
// Update the JSON from the design system, then run `node scripts/build-tokens.mjs`.
// lib/tokens.ts mirrors the same values for inline styles and SVG; keep it in step.
import { readFileSync, writeFileSync } from 'node:fs';

const t = JSON.parse(readFileSync(new URL('../design/tokens.json', import.meta.url), 'utf8'));
const byName = (family) => Object.fromEntries(t[family].tokens.map((x) => [x.name, x.value.light ?? x.value]));
const strip = (obj, prefix) => Object.fromEntries(Object.entries(obj).map(([k, v]) => [k.replace(prefix, ''), v]));

const preset = {
  theme: {
    extend: {
      colors: byName('color'),
      fontFamily: {
        display: ['Baloo2-Bold'],
        'display-semi': ['Baloo2-Bold'],
        numeric: ['Baloo2-ExtraBold'],
        body: ['Nunito-Regular'],
        'body-semi': ['Nunito-SemiBold'],
      },
      borderRadius: strip(byName('radius'), 'radius-'),
      boxShadow: strip(byName('shadow'), 'shadow-'),
    },
  },
};

writeFileSync(
  new URL('../tailwind.preset.js', import.meta.url),
  `// Beavo NativeWind/Tailwind preset — Riacho. Generated by scripts/build-tokens.mjs from design/tokens.json; don't hand-edit.\nmodule.exports = ${JSON.stringify(preset, null, 2)};\n`,
);
