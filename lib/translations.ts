export type Locale = 'en' | 'pt-BR' | 'es';

export const TABLES: Record<Locale, Table> = { en, 'pt-BR': ptBR, es };

/**
 * The first of the device's preferred languages that Beavo speaks. Any Portuguese
 * gets pt-BR and any Spanish gets `es`; everything else falls back to English.
 */
export function pickLocale(languageTags: readonly string[]): Locale {
  for (const tag of languageTags) {
    const language = tag.toLowerCase().split(/[-_]/)[0];
    if (language === 'pt') return 'pt-BR';
    if (language === 'es') return 'es';
    if (language === 'en') return 'en';
  }
  return 'en';
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  params: Record<string, string | number> = {},
): string {
  return TABLES[locale][key].replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    name in params ? String(params[name]) : placeholder,
  );
}
